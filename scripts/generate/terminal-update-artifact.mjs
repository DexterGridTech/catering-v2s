#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const schemaPath = 'contracts/terminal/terminal-update-artifact.schema.json';
const outputs = new Map([
  ['apps/terminal/kernel/base/platform-ports/src/generated/terminalUpdateArtifact.ts', generateTypeScript],
  [
    'apps/terminal/adapter/android/update/android/src/main/java/com/catering/v2s/terminal/adapter/android/update/generated/TerminalUpdateArtifact.kt',
    generateKotlin,
  ],
]);

function fail(code) {
  throw new Error(code);
}

function resolveInsideRoot(relative, base, marker) {
  if (typeof relative !== 'string' || !relative || path.isAbsolute(relative)) fail(marker);
  const absolute = path.resolve(base, relative);
  const lexical = path.relative(base, absolute);
  if (lexical === '..' || lexical.startsWith(`..${path.sep}`)) fail(marker);
  let actual;
  try {
    actual = fs.realpathSync(absolute);
  } catch {
    fail('TERMINAL_UPDATE_ARTIFACT_PATH_MISSING');
  }
  const realRoot = fs.realpathSync(base);
  const actualRelative = path.relative(realRoot, actual);
  if (actualRelative === '..' || actualRelative.startsWith(`..${path.sep}`)) fail(marker);
  return actual;
}

function readSchema(base) {
  const file = resolveInsideRoot(schemaPath, base, 'TERMINAL_UPDATE_ARTIFACT_PATH_ESCAPE');
  const schema = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (
    schema.$schema !== 'http://json-schema.org/draft-07/schema#' ||
    schema.title !== 'TER terminal update artifact' ||
    schema.type !== 'object' ||
    schema.additionalProperties !== false ||
    schema.properties?.schemaVersion?.const !== 1 ||
    schema.properties?.platform?.const !== 'android' ||
    schema.properties?.files?.items?.$ref !== '#/$defs/file' ||
    !schema.$defs?.file ||
    !schema.$defs?.minimumFull ||
    !schema.$defs?.apk
  ) {
    fail('TERMINAL_UPDATE_ARTIFACT_SCHEMA_INVALID');
  }
  return schema;
}

function generateTypeScript(schema) {
  return `// Generated by scripts/generate/terminal-update-artifact.mjs. Do not edit.
export interface TerminalUpdateArtifactFile {
  readonly path: string;
  readonly sizeBytes: number;
  readonly sha256: string;
}
export interface TerminalUpdateMinimumFull {
  readonly applicationId: string;
  readonly nativeBuildNumber: number;
  readonly runtimeVersion: string;
  readonly publicationId: string;
  readonly apkSha256: string;
}
export interface TerminalUpdateApkIdentity {
  readonly path: string;
  readonly sha256: string;
  readonly certificateSha256: string;
}
export interface TerminalUpdateArtifact {
  readonly schemaVersion: 1;
  readonly platform: 'android';
  readonly applicationId: string;
  readonly nativeVersion: string;
  readonly nativeBuildNumber: number;
  readonly bundleVersion: string;
  readonly runtimeVersion: string;
  readonly entry: string;
  readonly files: readonly TerminalUpdateArtifactFile[];
  readonly publicationId: string;
  readonly minimumFull?: TerminalUpdateMinimumFull;
  readonly apk?: TerminalUpdateApkIdentity;
}
`;
}

function generateKotlin() {
  return (
    `// Generated by scripts/generate/terminal-update-artifact.mjs. Do not edit.\n` +
    `package com.catering.v2s.terminal.adapter.android.update.generated\n\n` +
    `data class TerminalUpdateArtifactFile(val path: String, val sizeBytes: Long, val sha256: String)\n` +
    `data class TerminalUpdateMinimumFull(val applicationId: String, val nativeBuildNumber: Int, val runtimeVersion: String, val publicationId: String, val apkSha256: String)\n` +
    `data class TerminalUpdateApkIdentity(val path: String, val sha256: String, val certificateSha256: String)\n` +
    `data class TerminalUpdateArtifact(val schemaVersion: Int, val platform: String, val applicationId: String, val nativeVersion: String, val nativeBuildNumber: Int, val bundleVersion: String, val runtimeVersion: String, val entry: String, val files: List<TerminalUpdateArtifactFile>, val publicationId: String, val minimumFull: TerminalUpdateMinimumFull? = null, val apk: TerminalUpdateApkIdentity? = null)\n`
  );
}

function expected(base = root) {
  const schema = readSchema(base);
  return new Map([...outputs].map(([relative, render]) => [relative, render(schema)]));
}

function writeOrCheck(checkOnly) {
  const files = expected();
  for (const [relative, content] of files) {
    const target = path.join(root, relative);
    if (checkOnly) {
      if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== content)
        fail('TERMINAL_UPDATE_ARTIFACT_GENERATED_STALE');
      continue;
    }
    fs.mkdirSync(path.dirname(target), {recursive: true});
    fs.writeFileSync(target, content);
  }
  if (checkOnly) process.stdout.write('TERMINAL_UPDATE_ARTIFACT_GENERATOR_CHECK=PASS\n');
}

function selfTest() {
  const schema = readSchema(root);
  const altered = structuredClone(schema);
  altered.properties.schemaVersion.const = 2;
  try {
    if (altered.properties.schemaVersion.const !== 1) throw new Error('TERMINAL_UPDATE_ARTIFACT_SCHEMA_INVALID');
    fail('TERMINAL_UPDATE_ARTIFACT_SELF_TEST_POSITIVE_FAILED');
  } catch (error) {
    if (error.message !== 'TERMINAL_UPDATE_ARTIFACT_SCHEMA_INVALID') throw error;
  }
  const outside = path.resolve(root, '..', 'outside.json');
  try {
    resolveInsideRoot(path.relative(root, outside), root, 'TERMINAL_UPDATE_ARTIFACT_PATH_ESCAPE');
    fail('TERMINAL_UPDATE_ARTIFACT_SELF_TEST_ESCAPE_FAILED');
  } catch (error) {
    if (error.message !== 'TERMINAL_UPDATE_ARTIFACT_PATH_ESCAPE') throw error;
  }
  const temporaryRoot = fs.mkdtempSync(path.join(process.env.TMPDIR ?? '/tmp', 'ter-update-generator-'));
  const inputRoot = path.join(temporaryRoot, 'input-root');
  const escapedFile = path.join(temporaryRoot, 'escaped.json');
  fs.mkdirSync(inputRoot);
  fs.writeFileSync(escapedFile, '{}');
  fs.symlinkSync(escapedFile, path.join(inputRoot, 'schema.json'));
  try {
    resolveInsideRoot('schema.json', inputRoot, 'TERMINAL_UPDATE_ARTIFACT_PATH_ESCAPE');
    fail('TERMINAL_UPDATE_ARTIFACT_SELF_TEST_SYMLINK_FAILED');
  } catch (error) {
    if (error.message !== 'TERMINAL_UPDATE_ARTIFACT_PATH_ESCAPE') throw error;
  } finally {
    fs.rmSync(temporaryRoot, {recursive: true, force: true});
  }
  process.stdout.write('TERMINAL_UPDATE_ARTIFACT_SELF_TEST=PASS\n');
}

const args = process.argv.slice(2);
if (args.length !== 1 || !['--write', '--check', '--self-test'].includes(args[0]))
  fail('TERMINAL_UPDATE_ARTIFACT_USAGE');
if (args[0] === '--self-test') selfTest();
else writeOrCheck(args[0] === '--check');
